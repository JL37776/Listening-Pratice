function makeSentences(items, prefix) {
  return items.map((text, index) => ({
    id: `${prefix}-${String(index + 1).padStart(3, "0")}`,
    text,
    note: `Practice item ${index + 1}.`,
  }));
}

function makeInterviewItems() {
  const scenarioItems = interviewScenarios.map(([question, situation, task, action, result], index) => ({
    id: `nz-behavior-${String(index + 1).padStart(3, "0")}`,
    text: question,
    note: `Answer: Situation: ${situation} Task: ${task} Action: ${action} Result: ${result} Reflection: I learned to communicate early, stay calm, and focus on practical outcomes.`,
  }));

  const generatedItems = interviewPrompts.map((question, index) => {
    const number = index + scenarioItems.length + 1;
    return {
      id: `nz-behavior-${String(number).padStart(3, "0")}`,
      text: question,
      note: `Answer: Situation: In a previous role, I faced this kind of situation in a busy, service-focused workplace. Task: I needed to protect the outcome, keep people informed, and work in a way that matched New Zealand expectations around fairness, respect, and practical teamwork. Action: I clarified the real issue, listened before reacting, agreed on the next step, and followed through with clear communication. Result: The situation became more manageable, the team or customer had confidence in the plan, and I learned to combine initiative with humility and accountability.`,
    };
  });

  return [...scenarioItems, ...generatedItems];
}

